#!/usr/bin/env python
"""Profile the raw data -> docs/DATA_PROFILING.md + artifacts/reports/data_profile.json."""
import json
import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
from airbnb_dwh import config, silver  # noqa: E402


def md(df: pd.DataFrame) -> str:
    return df.to_markdown(index=False) if hasattr(df, "to_markdown") else df.to_string(index=False)


def main() -> None:
    raw = silver.read_raw()
    num = ["realSum", "person_capacity", "cleanliness_rating", "guest_satisfaction_overall", "bedrooms", "dist",
           "metro_dist", "attr_index", "attr_index_norm", "rest_index", "rest_index_norm", "lng", "lat"]
    df = raw.copy()
    for c in num + ["multi", "biz"]:
        df[c] = pd.to_numeric(df[c])
    data_cols = [c for c in raw.columns if c not in ("source_row_index", "source_file", "city", "day_type")]
    prof = {
        "rows": len(df), "files": int(df.source_file.nunique()), "cities": int(df.city.nunique()),
        "blank_cells": int((raw.replace("", pd.NA).isna()).sum().sum()),
        "exact_duplicate_rows_excluding_index": int(raw.duplicated(subset=data_cols).sum()),
        "source_row_index_restarts_per_file": bool(df.groupby("source_file").source_row_index.apply(lambda s: s.astype(int).min() == 0).all()),
        "multi_and_biz_both_1": int(((df.multi == 1) & (df.biz == 1)).sum()),
        "price_outliers_gt_5000": int((df.realSum > 5000).sum()),
        "price_p99": float(df.realSum.quantile(.99)), "price_max": float(df.realSum.max()),
        "has_calendar_date_column": False, "has_listing_id_column": False, "has_host_id_column": False,
        "has_property_type_column": False,
    }
    desc = df[num].describe(percentiles=[.01, .25, .5, .75, .99]).T.round(3).reset_index().rename(columns={"index": "column"})
    nulls = pd.DataFrame({"column": raw.columns, "blank_or_null": [int((raw[c] == "").sum()) for c in raw.columns],
                          "distinct": [int(raw[c].nunique()) for c in raw.columns]})
    city = df.groupby("city").agg(rows=("realSum", "size"), mean_price=("realSum", "mean"), median_price=("realSum", "median"),
                                  lat_min=("lat", "min"), lat_max=("lat", "max"), lng_min=("lng", "min"), lng_max=("lng", "max")).round(3).reset_index()
    room = df.room_type.value_counts().rename_axis("room_type").reset_index(name="rows")
    rating = pd.DataFrame({"cleanliness_rating": df.cleanliness_rating.value_counts().sort_index().index,
                           "rows": df.cleanliness_rating.value_counts().sort_index().values})
    sat = df.guest_satisfaction_overall.describe().round(2).to_frame("value").reset_index()
    q1, q3 = df.realSum.quantile([.25, .75])
    out_iqr = int((df.realSum > q3 + 1.5 * (q3 - q1)).sum())
    (ROOT / "artifacts/reports").mkdir(parents=True, exist_ok=True)
    (ROOT / "artifacts/reports/data_profile.json").write_text(json.dumps(
        {"summary": prof, "numeric_describe": json.loads(desc.to_json(orient="records")),
         "cities": json.loads(city.to_json(orient="records")), "room_types": json.loads(room.to_json(orient="records"))}, indent=2))
    text = f"""# Data Profiling (raw source, generated by `1_bronze_layer/validation/profile_data.py`)

Source: Zenodo DOI {config.SOURCE_DOI} (CC BY 4.0). All figures below are computed from the 20 raw CSV files.

## Summary
| Metric | Value |
|---|---|
| Files | {prof['files']} (10 cities x weekdays/weekends) |
| Rows | {prof['rows']:,} |
| Columns per file | 20 (1 unnamed exported row index + 19 analytical) |
| Blank / null cells | {prof['blank_cells']} |
| Exact duplicate rows (excluding index column) | {prof['exact_duplicate_rows_excluding_index']} |
| Rows with `multi`=1 and `biz`=1 together | {prof['multi_and_biz_both_1']} (mutually exclusive flags) |
| Prices > 5,000 EUR | {prof['price_outliers_gt_5000']} (max {prof['price_max']:.2f}, p99 {prof['price_p99']:.2f}) |
| Prices above Tukey upper fence (global) | {out_iqr} |

## Schema consistency
All 20 files share the *exact* same header (verified byte-for-byte in `data/manifests/bronze_manifest.csv`).
The first column is an unnamed zero-based index that restarts in every file (restarts in every file: {prof['source_row_index_restarts_per_file']}); it is **not** a listing id.

## Limitations confirmed from the data
* No calendar date column -> no Date dimension and no time series are possible.
* No listing id / host id column -> no Host or Property dimension, no listing-level deduplication.
* No property-type column; only `room_type` (Entire home/apt, Private room, Shared room).
* `realSum` = price for 2 guests x 2 nights in EUR (per the source paper/documentation), not a nightly rate.

## Numeric profile
{md(desc)}

## Blank counts and distinct values per column
{md(nulls)}

## Cities (rows, price, coordinate extent)
{md(city)}

## Room types
{md(room)}

## Cleanliness rating distribution
{md(rating)}

## Guest satisfaction distribution
{md(sat)}

## Semantics of ambiguous columns
| Column | Interpretation used | Basis |
|---|---|---|
| `realSum` | Total price, 2 persons, 2 nights, EUR, incl. fees | Zenodo paper / `SOURCE_MANIFEST.txt` |
| `multi`, `biz` | Host has 2-4 listings / more than 4 listings | Zenodo record column description (verified 2026-11-20); data agrees: flags never both 1 |
| `dist`, `metro_dist` | Distance (km) to city centre / nearest metro | Zenodo record column description; ranges 0.015-25.3 km and 0.002-14.3 km |
| `attr_index`, `rest_index` | Attraction / restaurant proximity indices (raw and 0-100 normalised) | Zenodo record column description; `*_norm` max = 100 |
| `lng`, `lat` | Listing coordinates (source data, jittered by Airbnb) | Source |
"""
    (ROOT / "docs").mkdir(exist_ok=True)
    (ROOT / "docs/DATA_PROFILING.md").write_text(text)
    print("profile written:", prof)


if __name__ == "__main__":
    main()
